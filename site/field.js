/* ==========================================================================
   Antaclis — live field-line animation for the hero

   A single magnetic dipole, drawn from the exact equation of its field lines
   in a plane through its axis: r = L sin^2(theta), one closed loop per L.
   Everything that moves is a smooth transformation of that ideal picture, so
   the lines are always clean loops and never break or tangle:
     - loops slowly expand: new ones appear at the centre, grow outwards and
       dissolve at the edges (an endless, seamless cycle);
     - the dipole sways around its axis and the shape breathes very slightly;
     - faint pulses travel along the lines, from the north to the south pole.
   All motion is livelier in the first seconds and settles to a slow drift.

   Without JavaScript, or when the visitor asks for reduced motion, this script
   does nothing and the static SVG generated by tools/fieldlines.py stays.
   ========================================================================== */
(() => {
  "use strict";

  const svg = document.querySelector("svg.field");
  if (!svg || !window.matchMedia || matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  const canvas = document.createElement("canvas");
  const ctx = canvas.getContext && canvas.getContext("2d");
  if (!ctx) return;

  /* ---- Parameters (units: the 640 x 500 SVG viewBox) ------------------- */
  const W = 640, H = 500;
  const CX = 300, CY = 250;   // centre of the dipole
  const TILT = 82;            // degrees; resting direction of the dipole (90 = up)
  const START_R = 4;          // lines start and end this far from the centre
  const RATIO = 1.33;         // size ratio between neighbouring loops
  const L_MIN = 12;           // smallest loop size (fully faded out)
  const LOOPS = 15;           // loops per side
  const FADE_OUT = [380, 700];// loops dissolve while their size grows across this range
  const SETTLE = 6;           // s, time constant from lively to subtle motion
  const GROW = 2.6;           // s, duration of the initial draw-in of each line
  const DRIFT_FAST = 0.45;    // loops per second that the pattern expands by, at first
  const DRIFT_SLOW = 0.05;    // ... and once settled
  const PULSE_SPEED = 70;     // units/s along a line
  const PULSE_LEN = 60;       // units
  const PULSE_GAP = 420;      // units of empty line between two pulses

  const rad = (deg) => (deg * Math.PI) / 180;
  const clamp01 = (v) => Math.min(1, Math.max(0, v));
  const ease = (v) => 1 - (1 - v) ** 3;
  const smooth = (a, b, v) => { const x = clamp01((v - a) / (b - a)); return x * x * (3 - 2 * x); };

  /* ---- State of the picture at time t (seconds) ------------------------ */
  function state(t) {
    const e = Math.exp(-t / SETTLE);
    const amp = 0.3 + 0.7 * e;                     // motion amplitude: 1 -> 0.3
    return {
      angle: rad(TILT + 12 * amp * Math.sin(0.42 * t) + 3 * Math.sin(0.07 * t)),
      sx: 1 + 0.05 * amp * Math.sin(0.33 * t),     // gentle breathing, never a distortion
      sy: 1 - 0.04 * amp * Math.sin(0.33 * t + 0.8),
      cx: CX + 5 * amp * Math.sin(0.21 * t),
      cy: CY + 4 * amp * Math.sin(0.27 * t + 1),
      // How far the loops have expanded, in loops: the integral of a drift speed
      // that decays from DRIFT_FAST to DRIFT_SLOW. Starts so that the first frame
      // matches the static SVG (loop sizes 34 x 1.33^k).
      drift: 0.63 + DRIFT_SLOW * t + (DRIFT_FAST - DRIFT_SLOW) * SETTLE * (1 - e),
    };
  }

  /* ---- Geometry --------------------------------------------------------- */
  // Polyline with cumulative arc lengths, for partial and pulse drawing.
  function polyline(pts) {
    const cum = [0];
    let len = 0;
    for (let i = 2; i < pts.length; i += 2) {
      len += Math.hypot(pts[i] - pts[i - 2], pts[i + 1] - pts[i - 1]);
      cum.push(len);
    }
    return { pts, cum, len };
  }

  // All lines for state s. Each has an id that stays the same while its loop
  // grows, so its pulse keeps moving smoothly, and an opacity (fades in at the
// core, out once the loop is large).
  function lines(s) {
    const ux = Math.cos(s.angle), uy = -Math.sin(s.angle); // along the dipole (SVG y points down)
    const wx = -uy, wy = ux;                                // perpendicular to it
    const place = (x, y, out) => out.push(s.cx + s.sx * (x * wx + y * ux), s.cy + s.sy * (x * wy + y * uy));

    const out = [];
    // The axis line, out of both poles.
    for (const sign of [1, -1]) {
      const p = [];
      place(0, sign * START_R, p);
      place(0, sign * 900, p);
      out.push({ ...polyline(p), id: sign, alpha: 1, order: 0 });
    }
    // Closed loops r = L sin^2(theta), from the north pole round to the south pole.
    const whole = Math.floor(s.drift), frac = s.drift - whole;
    for (let k = 0; k < LOOPS; k++) {
      const L = L_MIN * RATIO ** (k + frac);
      const alpha = smooth(L_MIN * 1.2, L_MIN * 3.2, L) * (1 - smooth(FADE_OUT[0], FADE_OUT[1], L));
      if (alpha <= 0) continue;
      const th0 = Math.asin(Math.sqrt(START_R / L));
      const n = Math.max(24, Math.min(360, Math.round(L / 2.5)));
      for (const side of [1, -1]) {
        const p = [];
        for (let i = 0; i <= n; i++) {
          const th = th0 + ((Math.PI - 2 * th0) * i) / n;
          const r = L * Math.sin(th) ** 2;
          place(side * r * Math.sin(th), r * Math.cos(th), p);
        }
        // k - whole identifies the loop independently of how far the pattern has expanded.
        out.push({ ...polyline(p), id: 10 * (k - whole) + side, alpha, order: Math.max(0, k - whole + 1) });
      }
    }
    return out;
  }

  /* ---- Drawing ---------------------------------------------------------- */
  let colour = "#8AB6F9", alpha = 0.6, scale = 1, dpr = 1;

  function readTheme() {
    const cs = getComputedStyle(canvas);
    colour = cs.getPropertyValue("--field").trim() || colour;
    alpha = parseFloat(cs.getPropertyValue("--field-alpha")) || alpha;
  }

  // Stroke the part of a line between arc lengths a and b.
  function strokeRange(l, a, b) {
    const { pts, cum } = l;
    a = Math.max(0, a); b = Math.min(l.len, b);
    if (b <= a) return;
    const at = (i, f) => [pts[2 * i - 2] + f * (pts[2 * i] - pts[2 * i - 2]),
                          pts[2 * i - 1] + f * (pts[2 * i + 1] - pts[2 * i - 1])];
    ctx.beginPath();
    let started = false;
    for (let i = 1; i < cum.length; i++) {
      if (cum[i] < a) continue;
      const seg = cum[i] - cum[i - 1] || 1;
      if (!started) { ctx.moveTo(...at(i, clamp01((a - cum[i - 1]) / seg))); started = true; }
      if (cum[i] >= b) { ctx.lineTo(...at(i, clamp01((b - cum[i - 1]) / seg))); break; }
      ctx.lineTo(pts[2 * i], pts[2 * i + 1]);
    }
    ctx.stroke();
  }

  function draw(t) {
    const ls = lines(state(t));
    ctx.setTransform(scale * dpr, 0, 0, scale * dpr, 0, 0);
    ctx.clearRect(0, 0, W, H);
    ctx.strokeStyle = colour;
    ctx.lineCap = "round";
    ctx.lineJoin = "round";

    // Base lines, growing in at the start (inner loops first).
    ctx.lineWidth = 1.15;
    for (const l of ls) {
      ctx.globalAlpha = alpha * 0.8 * l.alpha;
      strokeRange(l, 0, l.len * ease(clamp01((t - 0.2 - l.order * 0.09) / GROW)));
    }

    // Pulses travelling along the lines, fading in once the lines are drawn.
    const show = clamp01((t - GROW) / 2);
    if (show > 0) {
      ctx.lineWidth = 1.6;
      for (const l of ls) {
        const head = (t * PULSE_SPEED + l.id * 157) % (l.len + PULSE_GAP);
        for (let j = 0; j < 6; j++) {             // tail: brighter towards the head
          ctx.globalAlpha = show * l.alpha * Math.min(1, alpha * 1.6) * ((j + 1) / 6) ** 2;
          strokeRange(l, head - PULSE_LEN * (1 - j / 6), head - PULSE_LEN * (1 - (j + 1) / 6));
        }
      }
    }
    ctx.globalAlpha = 1;
  }

  /* ---- Set-up: swap the static SVG for the canvas ---------------------- */
  canvas.className = svg.getAttribute("class");
  canvas.setAttribute("role", "img");
  canvas.setAttribute("aria-label", svg.getAttribute("aria-label") || "");
  svg.replaceWith(canvas);
  readTheme();
  matchMedia("(prefers-color-scheme: light)").addEventListener?.("change", readTheme);

  // Match the canvas pixels to its displayed size. Returns true if it changed
  // (changing the size clears the canvas, so the caller must redraw).
  function resize() {
    const w = canvas.clientWidth;
    if (!w) return false;
    dpr = Math.min(2, window.devicePixelRatio || 1);
    scale = w / W;
    const bw = Math.round(w * dpr), bh = Math.round((w * H / W) * dpr);
    if (bw === canvas.width && bh === canvas.height) return false;
    canvas.width = bw;
    canvas.height = bh;
    return true;
  }

  // A fixed time can be set to render a single still frame (used for previews).
  if (typeof window.ANTACLIS_FIELD_T === "number") {
    resize(); draw(window.ANTACLIS_FIELD_T); return;
  }

  // Animation clock: advances only while the hero is on screen.
  let t = 0, last = 0, raf = 0, visible = true;
  function frame(now) {
    raf = requestAnimationFrame(frame);
    const dt = last ? Math.min(0.1, (now - last) / 1000) : 0;
    if (t > 3 * SETTLE && now - last < 1000 / 31) return; // 30 fps once the motion is subtle
    last = now;
    t += dt;
    draw(t);
  }
  function start() { if (!raf && visible) { last = 0; raf = requestAnimationFrame(frame); } }
  function stop() { cancelAnimationFrame(raf); raf = 0; }

  new ResizeObserver(() => { if (resize()) draw(t); }).observe(canvas);
  new IntersectionObserver(([entry]) => {
    visible = entry.isIntersecting;
    visible ? start() : stop();
  }).observe(canvas);
  resize();
  start();
})();
